def multiply(a, b):
    """
    Multiply two numbers and return their product.

    Args:
        a: First number (int or float)
        b: Second number (int or float)

    Returns:
        The product of a and b

    Examples:
        >>> multiply(3, 4)
        12
        >>> multiply(2.5, 4)
        10.0
        >>> multiply(-3, 5)
        -15
        >>> multiply(0, 100)
        0
    """
    return a * b
