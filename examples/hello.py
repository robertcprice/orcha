#!/usr/bin/env python3
"""
Hello Function
A simple function that returns a greeting message.
"""


def hello():
    """
    Return the greeting 'Hello, World!'

    Returns:
        str: The string 'Hello, World!'
    """
    return 'Hello, World!'


def main():
    """Print Hello, World! to the console."""
    print(hello())


if __name__ == "__main__":
    main()
