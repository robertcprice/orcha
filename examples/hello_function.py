"""
Hello function module.

This module provides a simple hello function that returns a greeting message.
"""


def hello():
    """
    Return a greeting message.

    Returns:
        str: The greeting message 'Hello, World!'

    Examples:
        >>> hello()
        'Hello, World!'
    """
    return "Hello, World!"


if __name__ == "__main__":
    # Example usage
    print(hello())
